import React from 'react';
import { 
  CheckCircle, 
  AlertTriangle, 
  AlertOctagon, 
  Download, 
  Layers, 
  BarChart, 
  Info,
  Clock,
  Activity
} from 'lucide-react';

export default function AssessmentPanel({ result, onExport }) {
  if (!result) {
    return (
      <div className="card assessment-card-empty">
        <Activity className="w-10 h-10 text-slate-300 mx-auto mb-3" />
        <h3 className="empty-title">Ready for Inference</h3>
        <p className="empty-text">
          Select a test case or adjust parameters and click &ldquo;Run Prediction Model&rdquo; to view classification probabilities and engineering recommendations.
        </p>
      </div>
    );
  }

  const { prediction, probabilities, recommendation, inputs } = result;

  const isGood = prediction === 'Good';
  const isWeak = prediction === 'Weak';
  const isDanger = !isGood && !isWeak;

  const badgeStyle = isGood 
    ? 'result-banner-good' 
    : isWeak 
    ? 'result-banner-weak' 
    : 'result-banner-danger';

  const icon = isGood ? (
    <CheckCircle className="w-6 h-6 text-emerald-600" />
  ) : isWeak ? (
    <AlertTriangle className="w-6 h-6 text-amber-600" />
  ) : (
    <AlertOctagon className="w-6 h-6 text-rose-600" />
  );

  // Derived engineering metrics
  const signalDbm = inputs?.signal_strength ?? -60;
  const wifiNoise = inputs?.wifi_strength ?? -50;
  const estSnr = (signalDbm - (wifiNoise - 25)).toFixed(1);
  const rainLoss = ((inputs?.precipitation ?? 0) * 0.18).toFixed(1);
  const linkMargin = (signalDbm - (-95)).toFixed(1);

  return (
    <div className="card assessment-card">
      <div className="card-header-clean">
        <div>
          <h2 className="card-title">Prediction Result &amp; Analysis</h2>
          <p className="card-subtitle">
            Output generated by trained Random Forest Classifier.
          </p>
        </div>
        <button
          type="button"
          onClick={onExport}
          className="btn-secondary"
          title="Save prediction and parameters to JSON report"
        >
          <Download className="w-3.5 h-3.5 mr-1.5 inline" />
          Export Report
        </button>
      </div>

      {/* Main Classification Banner */}
      <div className={`result-banner ${badgeStyle}`}>
        <div className="result-banner-icon">
          {icon}
        </div>
        <div className="result-banner-text">
          <span className="result-sub-label">CLASSIFIED LINK STATE</span>
          <h3 className="result-class-name">{prediction}</h3>
          <p className="result-class-desc">
            {isGood && 'Signal parameters satisfy link budget requirements with nominal packet loss.'}
            {isWeak && 'Margin degradation observed; signal is susceptible to fading or bit errors.'}
            {isDanger && 'Link threshold violated; loss of synchronization or connection drop imminent.'}
          </p>
        </div>
      </div>

      {/* Probability Distribution Graph */}
      <div className="probability-section">
        <h4 className="section-sub-title">Class Probability Distribution</h4>
        <div className="prob-bars">
          {Object.entries(probabilities).map(([className, percent]) => {
            const barClass = className === 'Good' 
              ? 'bar-good' 
              : className === 'Weak' 
              ? 'bar-weak' 
              : 'bar-danger';

            return (
              <div key={className} className="prob-item">
                <div className="prob-info-row">
                  <span className="prob-label">{className}</span>
                  <span className="prob-percent font-mono">{percent.toFixed(1)}%</span>
                </div>
                <div className="prob-track">
                  <div
                    className={`prob-fill ${barClass}`}
                    style={{ width: `${percent}%` }}
                  />
                </div>
              </div>
            );
          })}
        </div>
      </div>

      {/* Engineering Link Parameters Grid */}
      <div className="metrics-grid">
        <div className="metric-box">
          <span className="metric-box-label">Estimated SNR / CNR</span>
          <strong className="metric-box-val font-mono">{estSnr} dB</strong>
          <span className="metric-box-sub">Carrier to Noise Ratio</span>
        </div>
        <div className="metric-box">
          <span className="metric-box-label">Rain Fade Loss</span>
          <strong className="metric-box-val font-mono text-blue-600">-{rainLoss} dB</strong>
          <span className="metric-box-sub">Hydrometeor Absorption</span>
        </div>
        <div className="metric-box">
          <span className="metric-box-label">Link Fade Margin</span>
          <strong className={`metric-box-val font-mono ${Number(linkMargin) > 10 ? 'text-emerald-600' : 'text-amber-600'}`}>
            +{linkMargin} dB
          </strong>
          <span className="metric-box-sub">Above -95 dBm floor</span>
        </div>
        <div className="metric-box">
          <span className="metric-box-label">Modulation Profile</span>
          <strong className="metric-box-val font-mono">
            {isGood ? '16-QAM (Rate 3/4)' : isWeak ? 'QPSK (Rate 1/2)' : 'BPSK Fallback'}
          </strong>
          <span className="metric-box-sub">Recommended Adaptive Rate</span>
        </div>
      </div>

      {/* Recommendation Card */}
      <div className="recommendation-card">
        <div className="recommendation-title">
          <Info className="w-4 h-4 text-blue-600 mr-1.5 inline" />
          <span>Operational Recommendation</span>
        </div>
        <p className="recommendation-text">
          {recommendation}
        </p>
      </div>
    </div>
  );
}
